// Scoring functions
export const calculateTWKScore = (answers: Record<number, string>): number => {
  let score = 0;
  questions.filter(q => q.category === 'TWK').forEach(q => {
    if (answers[q.id] === q.correctAnswer) {
      score += 5;
    }
  });
  return score;
};

export const calculateTIUScore = (answers: Record<number, string>): number => {
  let score = 0;
  questions.filter(q => q.category === 'TIU').forEach(q => {
    if (answers[q.id] === q.correctAnswer) {
      score += 5;
    }
  });
  return score;
};

export const calculateTKPScore = (answers: Record<number, string>): number => {
  let score = 0;
  questions.filter(q => q.category === 'TKP').forEach(q => {
    const selectedOption = q.options.find(opt => opt.key === answers[q.id]);
    if (selectedOption?.score) {
      score += selectedOption.score;
    }
  });
  return score;
};

export const getPassingStatus = (twk: number, tiu: number, tkp: number): { passed: boolean; message: string } => {
  const total = twk + tiu + tkp;
  
  // Passing Grade CPNS 2024
  const twkPass = twk >= 65;
  const tiuPass = tiu >= 80;
  const tkpPass = tkp >= 166;
  
  if (twkPass && tiuPass && tkpPass) {
    return { passed: true, message: 'LULUS - Semua nilai memenuhi passing grade!' };
  }
  
  const failedCategories = [];
  if (!twkPass) failedCategories.push(`TWK (${twk}/65)`);
  if (!tiuPass) failedCategories.push(`TIU (${tiu}/80)`);
  if (!tkpPass) failedCategories.push(`TKP (${tkp}/166)`);
  
  return { 
    passed: false, 
    message: `TIDAK LULUS - Belum memenuhi passing grade: ${failedCategories.join(', ')}` 
  };
};
